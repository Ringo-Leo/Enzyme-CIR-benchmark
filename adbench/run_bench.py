#!/usr/bin/env python3
import argparse
import glob
import json
import os
import subprocess
import sys
import time
ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
BIN = os.path.join(ROOT, 'build')
TMP = os.path.join(ROOT, 'tmp', 'Release')
PYTHON = os.environ.get('ADBENCH_PYTHON', sys.executable)
DEFAULT_TOLERANCE = 1e-08
TOOLS = [('Manual', 'cpp', 'gmm ba hand lstm', None), ('ManualEigen', 'cpp', 'gmm ba hand lstm', DEFAULT_TOLERANCE), ('ManualEigenVector', 'cpp', 'gmm', DEFAULT_TOLERANCE), ('Finite', 'cpp', 'gmm ba hand lstm', 0.0001), ('FiniteEigen', 'cpp', 'hand', 0.0001), ('Tapenade', 'cpp', 'gmm ba hand lstm', DEFAULT_TOLERANCE), ('EnzymeCIR', 'cpp', 'gmm ba hand lstm', DEFAULT_TOLERANCE), ('EnzymeLLVM', 'cpp', 'gmm ba hand lstm', DEFAULT_TOLERANCE), ('PyTorch', 'python', 'gmm ba hand lstm', 1e-07), ('Autograd', 'py', 'gmm ba', None)]

def tests(objective, quick):
    if objective == 'gmm':
        ds, ks = ([2], [5]) if quick else ([2, 10, 20, 32, 64], [5, 10, 25, 50, 100])
        return [[('GMM', 'data/gmm/1k/', 'gmm/1k', f'gmm_d{d}_K{k}') for k in ks] for d in ds]
    if objective == 'ba':
        ns = [1] if quick else range(1, 6)
        names = [os.path.basename(glob.glob(os.path.join(ROOT, f'data/ba/ba{n}_*.txt'))[0])[:-4] for n in ns]
        return [[('BA', 'data/ba/', 'ba', fn) for fn in names]]
    if objective == 'hand':
        ns = [1] if quick else range(1, 6)
        chains = []
        for kind, task in (('simple', 'Hand'), ('complicated', 'Hand-Complicated')):
            dir_in = f'data/hand/{kind}_small/'
            names = [os.path.basename(glob.glob(os.path.join(ROOT, dir_in, f'hand{n}_*.txt'))[0])[:-4] for n in ns]
            chains.append([(task, dir_in, f'hand/{kind}_small', fn) for fn in names])
        return chains
    if objective == 'lstm':
        ls, cs = ([2], [1024]) if quick else ([2, 4], [1024, 4096])
        return [[('LSTM', 'data/lstm/', 'lstm', f'lstm_l{l}_c{c}') for c in cs] for l in ls]
    raise ValueError(objective)

def command(tool, kind, task, dir_in, dir_out, fn, a):
    run = [str(a.min_time), str(a.nruns_f), str(a.nruns_j), str(a.time_limit)]
    if kind == 'cpp':
        module = os.path.join(BIN, 'src/cpp/modules', tool[0].lower() + tool[1:], tool + '.dll')
        return [os.path.join(BIN, 'src/cpp/runner/CppRunner.exe'), task, module, os.path.join(ROOT, dir_in, fn + '.txt'), dir_out] + run
    if kind == 'python':
        suffix = 'Hand' if task.startswith('Hand') else task
        module = os.path.join(ROOT, 'src/python/modules', tool, f'{tool}{suffix}.py')
        return [PYTHON, os.path.join(ROOT, 'src/python/runner/main.py'), task.upper(), module, os.path.join(ROOT, dir_in, fn + '.txt'), dir_out] + run
    if kind == 'py':
        script = {'GMM': 'gmm_full', 'BA': 'ba'}[task]
        return [PYTHON, os.path.join(ROOT, 'tools', tool, f'{tool}_{script}.py'), os.path.join(ROOT, dir_in), dir_out, fn, str(a.nruns_f), str(a.nruns_j), str(a.time_limit)]
    raise ValueError(kind)

def write_timeout(path, why):
    with open(path, 'w') as f:
        f.write(f'inf inf\ntf tJ\nFile generated by run_bench.py: {why}\n')

def tokens(path):
    with open(path) as f:
        return [[float(t) for t in line.split()] for line in f if line.strip()]

def difference(x, y):
    if x == y:
        return 0.0
    norm = min(abs(x) + abs(y), sys.float_info.max)
    return abs(x - y) / norm if norm > 1.0 else abs(x - y)

def compare(golden, path, tolerance):
    result = {'File1': golden, 'File2': path, 'Tolerance': tolerance, 'DimensionMismatch': False, 'ParseError': False, 'MaxDifference': 0.0, 'AvgDifference': 0.0, 'DifferenceViolationCount': 0, 'NumberComparisonCount': 0, 'DifferenceViolations': [], 'Error': ''}
    try:
        a, b = (tokens(golden), tokens(path))
    except (OSError, ValueError) as e:
        result.update(ParseError=True, Error=str(e))
    else:
        if [len(r) for r in a] != [len(r) for r in b]:
            result.update(DimensionMismatch=True, Error='Dimension mismatch')
        else:
            total = 0.0
            for y, (ra, rb) in enumerate(zip(a, b)):
                for x, (va, vb) in enumerate(zip(ra, rb)):
                    d = difference(va, vb)
                    if not d <= tolerance:
                        result['DifferenceViolationCount'] += 1
                        if len(result['DifferenceViolations']) < 10:
                            result['DifferenceViolations'].append([x, y])
                    result['MaxDifference'] = max(result['MaxDifference'], d)
                    total += d
                    result['NumberComparisonCount'] += 1
            if result['NumberComparisonCount']:
                result['AvgDifference'] = total / result['NumberComparisonCount']
    result['ViolationsHappened'] = result['ParseError'] or result['DimensionMismatch'] or result['DifferenceViolationCount'] > 0
    return result

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--quick', action='store_true')
    p.add_argument('--tools', default=','.join((t[0] for t in TOOLS)))
    p.add_argument('--objectives', default='gmm,ba,hand,lstm')
    p.add_argument('--min-time', type=float, default=0.1)
    p.add_argument('--nruns-f', type=int, default=5)
    p.add_argument('--nruns-j', type=int, default=5)
    p.add_argument('--time-limit', type=float, default=5)
    p.add_argument('--timeout', type=float, default=180)
    a = p.parse_args()
    wanted = a.tools.split(',')
    summary = []
    for objective in a.objectives.split(','):
        for tool, kind, objectives, tolerance in TOOLS:
            if tool not in wanted or objective not in objectives.split():
                continue
            for chain in tests(objective, a.quick):
                timed_out = False
                for task, dir_in, rel, fn in chain:
                    dir_out = os.path.join(TMP, rel, tool) + '/'
                    os.makedirs(dir_out, exist_ok=True)
                    times = os.path.join(dir_out, f'{fn}_times_{tool}.txt')
                    if timed_out:
                        write_timeout(times, 'a smaller test timed out')
                        summary.append((tool, fn, 'skipped', ''))
                        continue
                    cmd = command(tool, kind, task, dir_in, dir_out, fn, a)
                    start = time.time()
                    status = 'ok'
                    try:
                        r = subprocess.run(cmd, cwd=ROOT, timeout=a.timeout, capture_output=True, text=True)
                        if not os.path.exists(times) or r.returncode not in (0, None):
                            if not os.path.exists(times):
                                write_timeout(times, f'exit code {r.returncode}')
                            status = f'failed ({r.returncode}): {(r.stderr or r.stdout).strip()[-200:]}'
                    except subprocess.TimeoutExpired:
                        write_timeout(times, f'killed after {a.timeout} s')
                        status = 'timeout'
                        timed_out = True
                    note = ''
                    golden = os.path.join(TMP, rel, 'Manual', f'{fn}_J_Manual.txt')
                    jac = os.path.join(dir_out, f'{fn}_J_{tool}.txt')
                    if tolerance is not None and status == 'ok':
                        c = compare(golden, jac, tolerance)
                        with open(os.path.join(dir_out, f'{fn}_correctness_{tool}.txt'), 'w') as f:
                            json.dump(c, f, indent=2)
                        note = ('WRONG' if c['ViolationsHappened'] else 'correct') + f" (max diff {c['MaxDifference']:.2e})"
                    with open(times) as f:
                        t = f.read().split()[:2]
                    print(f'{tool:18} {fn:32} {status:8} F={t[0]:>12} J={t[1]:>12} {note} [{time.time() - start:.1f}s]', flush=True)
                    summary.append((tool, fn, status, note))
    bad = [s for s in summary if 'WRONG' in s[3] or s[2].startswith('failed')]
    print(f'\n{len(summary)} runs, {len(bad)} wrong or failed')
    for s in bad:
        print('  ', *s)
if __name__ == '__main__':
    main()
